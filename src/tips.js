function tipFor(item) {
  if (!item || item.sep) return '';
  return TIPS[`${item.cmd}:${item.arg}`] || TIPS[item.cmd] || '';
}
const withTip = (item) => (item.sep ? item : { ...item, tip: tipFor(item) });

